/**
 * Relationship model — M3.5.
 *
 * Authority: IMPLEMENTATION_PLAN.md §7 ("M3.5 — Relationship model: Every
 * relationship contains source, destination, type, direction where
 * meaningful, visible label, and canonical destination. Visual
 * relationships may only represent semantic relationships present in
 * data."); INFORMATION_ARCHITECTURE.md §5 (Cross-District Relationship
 * Model); CROSS_UNIVERSE_SYSTEM_REQUIREMENTS.md §7 (Cross-District
 * Relationship Requirements). See
 * docs/implementation/M3.5_RELATIONSHIP_MODEL.md for the full audit,
 * including the reconciliation with M3.1's existing relationship
 * reference structure.
 *
 * M3.1 RECONCILIATION — this module does NOT introduce a second
 * relationship system. `CanonicalRelationshipReference { targetId; type;
 * priority? }` (M3.1, `CanonicalRecord.ts`) already stores source
 * (implicitly — the containing record's own `id`), destination
 * (`targetId`), type, and priority; `registry.ts`'s
 * `assertRelationshipsResolve` already rejects unresolved targets. This
 * module is the smallest addition needed to complete M3.5's exact scope
 * on top of that existing structure: self/duplicate-edge rejection,
 * canonical-destination resolution through M3.3's `resolveCanonicalRoute`,
 * and derived (never separately stored) visible labels, in both
 * directions.
 *
 * SIX-TYPE ONTOLOGY — unchanged from M3.1: `related-to`, `derived-from`,
 * `informed-by`, `tested-in`, `developed-into`, `commercialized-as`. This
 * module adds no seventh type, even though several Universe/Cross-Universe
 * documents use richer editorial phrasing (see `RELATIONSHIP_LABELS`
 * below) — those phrases become derived label TEXT, never new stored
 * types (IA §5.3: "the vocabulary is intentionally small").
 *
 * VISUAL BOUNDARY — this module produces data only: resolved targets,
 * routes, and label strings. No CSS, no Trace/Signal, no rendering. A
 * future presentation layer consuming this module's output is exactly
 * what `IMPLEMENTATION_PLAN.md`'s "visual relationships may only
 * represent semantic relationships present in data" requires — the data
 * this module exposes IS that semantic source.
 */

import type {
  CanonicalRecordBase,
  CanonicalRecordId,
  CanonicalRelationshipReference,
  CanonicalRelationshipType,
} from "./CanonicalRecord";
import { resolveCanonicalRoute } from "./RouteResolver";
import type { CanonicalRoute } from "./RouteResolver";

// ---------------------------------------------------------------------
// Visible label — derived, never stored. IA §5.4: "the displayed
// reciprocal wording may be adapted to context without changing the
// stored relationship." One reasonable default label per type and
// direction is provided; a future presentation layer may adapt wording
// further by context without needing a new stored type or a change here.
// Reverse-direction wording draws on the richer editorial vocabulary
// CROSS_UNIVERSE_SYSTEM_REQUIREMENTS.md and the district Universe
// documents already use for the SAME six semantic edges (e.g. Research
// Universe §9's "Reframed by"/"Generated by" for the reverse of
// `informed-by`/`tested-in`) — mapped onto the existing ontology, never
// expanding it.
// ---------------------------------------------------------------------

const RELATIONSHIP_LABELS: Record<CanonicalRelationshipType, { forward: string; reverse: string }> =
  {
    "related-to": { forward: "Related to", reverse: "Related to" },
    "derived-from": { forward: "Derived from", reverse: "Basis for" },
    "informed-by": { forward: "Informed by", reverse: "Informs" },
    "tested-in": { forward: "Tested in", reverse: "Tests" },
    "developed-into": { forward: "Developed into", reverse: "Developed from" },
    "commercialized-as": { forward: "Commercialized as", reverse: "Commercial origin of" },
  };

export type RelationshipDirection = "forward" | "reverse";

/** Derives a public-facing label for a stored relationship type and direction — pure text, never a new stored type. */
export function deriveRelationshipLabel(
  type: CanonicalRelationshipType,
  direction: RelationshipDirection = "forward",
): string {
  return RELATIONSHIP_LABELS[type][direction];
}

// ---------------------------------------------------------------------
// Validation — self-loops and duplicate edges (not covered by M3.1's
// `assertRelationshipsResolve`, which only checks target existence).
// ---------------------------------------------------------------------

export interface RelationshipIssue {
  path: string;
  message: string;
}

/**
 * Validates one record's outgoing relationships: rejects a self-loop
 * (source === destination), an unresolved target, and a duplicate edge
 * (same destination + same type referenced more than once). Complements,
 * rather than replaces, M3.1's `assertRelationshipsResolve`.
 */
export function validateRelationships(
  record: Pick<CanonicalRecordBase, "id" | "relationships">,
  registry: ReadonlyMap<CanonicalRecordId, CanonicalRecordBase>,
): RelationshipIssue[] {
  const issues: RelationshipIssue[] = [];
  const relationships = record.relationships ?? [];
  const seen = new Set<string>();

  relationships.forEach((relationship, index) => {
    const path = `relationships[${index}]`;

    if (relationship.targetId === record.id) {
      issues.push({
        path,
        message: `self-relationship rejected — source and destination are the same record ("${record.id}")`,
      });
    }

    if (!registry.has(relationship.targetId)) {
      issues.push({ path, message: `unresolved relationship target "${relationship.targetId}"` });
    }

    const key = `${relationship.targetId}::${relationship.type}`;
    if (seen.has(key)) {
      issues.push({
        path,
        message: `duplicate relationship — source "${record.id}" already has a "${relationship.type}" relationship to "${relationship.targetId}"`,
      });
    }
    seen.add(key);
  });

  return issues;
}

// ---------------------------------------------------------------------
// Canonical-destination resolution — target ID → target record (via a
// registry, e.g. M3.1's `createRecordRegistry`) → canonical route (via
// M3.3's `resolveCanonicalRoute`). No route string is ever persisted on
// the relationship reference itself; it is always resolved fresh.
// ---------------------------------------------------------------------

export interface ResolvedRelationship {
  sourceId: CanonicalRecordId;
  targetId: CanonicalRecordId;
  type: CanonicalRelationshipType;
  priority?: number;
  targetRoute: CanonicalRoute;
  label: string;
}

/** Resolves one outgoing relationship into its full public shape: target route (M3.3) and forward-direction label. Throws if the target is unresolved — callers should validate first via `validateRelationships`. */
export function resolveRelationship(
  record: Pick<CanonicalRecordBase, "id">,
  relationship: CanonicalRelationshipReference,
  registry: ReadonlyMap<CanonicalRecordId, CanonicalRecordBase>,
): ResolvedRelationship {
  const target = registry.get(relationship.targetId);
  if (!target) {
    throw new Error(`Cannot resolve relationship — unknown target "${relationship.targetId}"`);
  }
  return {
    sourceId: record.id,
    targetId: relationship.targetId,
    type: relationship.type,
    priority: relationship.priority,
    targetRoute: resolveCanonicalRoute(target),
    label: deriveRelationshipLabel(relationship.type, "forward"),
  };
}

// ---------------------------------------------------------------------
// Outgoing / incoming queries — the smallest capability needed to prove
// reciprocal display can be derived without persisting a duplicate
// inverse edge (IA §5.2: "the system may derive a reciprocal display...
// a separately authored reverse relationship is not required"). Not a
// graph-database abstraction — a plain scan over an already-loaded record
// set, the same scale M3.1's `registry.ts` already operates at.
// ---------------------------------------------------------------------

export function listOutgoingRelationships(
  record: Pick<CanonicalRecordBase, "relationships">,
): readonly CanonicalRelationshipReference[] {
  return record.relationships ?? [];
}

export interface IncomingRelationship {
  sourceId: CanonicalRecordId;
  type: CanonicalRelationshipType;
  priority?: number;
  label: string;
}

/** Derives every incoming edge for `targetId` by scanning the record set's outgoing relationships — never a separately stored/persisted reverse edge. */
export function listIncomingRelationships(
  targetId: CanonicalRecordId,
  records: readonly CanonicalRecordBase[],
): IncomingRelationship[] {
  const incoming: IncomingRelationship[] = [];
  for (const record of records) {
    for (const relationship of record.relationships ?? []) {
      if (relationship.targetId === targetId) {
        incoming.push({
          sourceId: record.id,
          type: relationship.type,
          priority: relationship.priority,
          label: deriveRelationshipLabel(relationship.type, "reverse"),
        });
      }
    }
  }
  return incoming;
}
